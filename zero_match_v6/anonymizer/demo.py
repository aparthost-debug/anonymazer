def _cities(n, rng):
    """~88% — четыре крупных города, остальное — редкие (по 3 записи) -> «Другое»."""
    rare_groups = n // 25
    rare = [f"МалыйГород_{i + 1}" for i in range(rare_groups) for _ in range(3)]
    main_n = n - len(rare)
    shares = [("Москва", .48), ("Санкт-Петербург", .20), ("Тверь", .10), ("Казань", .10)]
    total = sum(s for _, s in shares)
    out = []
    for name, sh in shares[1:]:
        out += [name] * int(main_n * sh / total)
    out = ["Москва"] * (main_n - len(out)) + out
    cities = out + rare
    rng.shuffle(cities)
    return cities


def generate_demo_data(n, seed=42):
    rng = random.Random(seed)
    np_rng = np.random.default_rng(seed)
    if n == 6:
        return pd.DataFrame({
            'ФИО': ['Иванов Иван', 'Смирнова Анна', 'Петров Пётр', 'Кузнецова Елена',
                    'Соколов Олег', 'Морозова Мария'],
            'Город': ['Москва', 'Москва', 'Москва', 'Тверь', 'Казань', 'Санкт-Петербург'],
            'Возраст': [25, 34, 41, 29, 52, 38],
            'Сумма_покупок': [15000, 89000, 23000, 120000, 45000, 67000],
            'История_действий': HISTORIES,
            'Комментарий_менеджера': [
                'Перезвонить +7 (999) 111-22-33', 'Почта клиента: anna@example.ru',
                'Постоянный покупатель. Анне подарок', 'Тел для связи 89165554433',
                'Запрос скидки 5%. Порекомендовал друг Петров',
                'VIP-клиент, email: vip_tver@mail.ru'],
            'Лояльный': ['нет', 'нет', 'да', 'нет', 'да', 'да'],
        })
    ages = np_rng.integers(25, 61, n)
    return pd.DataFrame({
        'ФИО': [f"{rng.choice(LAST)} {rng.choice(FIRST)}" for _ in range(n)],
        'Город': _cities(n, rng),
        'Возраст': ages.tolist(),
        'Сумма_покупок': np_rng.lognormal(10, 0.8, n).clip(1000, 500000).round(0).tolist(),
        'История_действий': [rng.choice(HISTORIES) for _ in range(n)],
        'Комментарий_менеджера': [rng.choice(COMMENTS) for _ in range(n)],
        # цель для ML-бенчмарка: зависит от возраста и не обрабатывается конвейером
        'Лояльный': np.where(ages + np_rng.normal(0, 5, n) > 43, 'да', 'нет').tolist(),
    })
